// Build-time data pipeline: fetch CityCatalyst's HIAP action library once and
// emit a committed TS module so the app builds offline and reproducibly.
//
//   node scripts/fetch-climate-actions.mjs
//
// Source: GET https://api.citycatalyst.io/api/v0/climate_actions?language=all
// (~155 city-agnostic actions, full EN/ES/PT i18n, HIAP schema). We do the
// per-city prioritization ourselves (see src/app/lib/prioritize.ts) because the
// per-city ranking endpoints aren't populated in prod yet.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "src", "app", "data", "climateActions.generated.ts");
const URL = "https://api.citycatalyst.io/api/v0/climate_actions?language=all";

const HAZARD_KEYS = [
  "droughts", "heatwaves", "floods", "sea-level-rise",
  "landslides", "storms", "wildfires", "diseases",
];

const lang = (v) => {
  // Normalize a possibly-partial i18n object to {en,es,pt}, falling back to en.
  if (v == null) return { en: "", es: "", pt: "" };
  if (typeof v === "string") return { en: v, es: v, pt: v };
  const en = v.en ?? v.es ?? v.pt ?? "";
  return { en, es: v.es ?? en, pt: v.pt ?? en };
};
const arr = (v) => (Array.isArray(v) ? v.filter(Boolean) : v ? [v] : []);

function transform(a) {
  const types = arr(a.ActionType);
  return {
    actionId: a.ActionID,
    name: lang(a.ActionName),
    description: lang(a.Description),
    actionType: types.includes("adaptation") ? "adaptation" : "mitigation",
    hazards: arr(a.Hazard).filter((h) => HAZARD_KEYS.includes(h)),
    sectors: arr(a.Sector),
    coBenefits: a.CoBenefits ?? {},
    ghgReductionPotential: a.GHGReductionPotential ?? {},
    adaptationEffectiveness: a.AdaptationEffectiveness ?? null,
    adaptationPerHazard: a.AdaptationEffectivenessPerHazard ?? {},
    cost: a.CostInvestmentNeeded ?? null,
    timeline: a.TimelineForImplementation ?? null,
    biome: a.biome ?? null,
    category: a.ActionCategory ?? null,
    keyImpacts: typeof a.KeyImpacts === "string" ? a.KeyImpacts : null,
  };
}

const res = await fetch(URL);
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
const raw = await res.json();
const actions = raw.map(transform);
const stamp = new Date().toISOString().slice(0, 10);

const header = `// AUTO-GENERATED by scripts/fetch-climate-actions.mjs — do not edit by hand.
// Source: ${URL}
// Fetched: ${stamp} · ${actions.length} actions (CityCatalyst HIAP library, EN/ES/PT).
import type { ClimateAction } from "./climateActions";

export const climateActions: ClimateAction[] = `;

writeFileSync(OUT, header + JSON.stringify(actions, null, 2) + ";\n");
console.log(`Wrote ${actions.length} actions to ${OUT}`);
